use strict;
use warnings;
use Getopt::Long;
use Data::Dumper;
use IO::Zlib;
use FindBin;
use lib "$FindBin::Bin/../00_Configuration";
use ProjectConfig qw(load_config);

my %cfg = load_config();

#######################################################################################
#######################################################################################
######     		     			 Initialize And Declare  	  		   			 ######
#######################################################################################
#######################################################################################

my 	$FileHandle								= new IO::Zlib;
my 	$RepeatLength							= 11;
my 	$NrFirstFile							= 0;
my 	$Chrom									= 1;

#######################################################################################
#######################################################################################
######     		     			  	  Get Options   	  		   			 	 ######
#######################################################################################
#######################################################################################

GetOptions ("RepeatLength=s"				=>	\$RepeatLength,
			"NrFirstFile=i"					=>	\$NrFirstFile,
			"Chrom=s"						=>	\$Chrom);

#######################################################################################
#######################################################################################
######     		     			 Initialize And Declare  	  		   			 ######
#######################################################################################
#######################################################################################

my 	$ConvDir 								= "$cfg{paths}{conv_dir}/$RepeatLength/";
my 	$FilePathToSummarize					= $ConvDir . "ToSummarize.repsum.geneconv.$Chrom.txt";
my 	$ChromQm								= quotemeta($Chrom);

#######################################################################################
#######################################################################################
######     		     	   Put Files To Summarize Into Array  	  				 ######
#######################################################################################
#######################################################################################

open F, "$FilePathToSummarize" or die ("Can't open $FilePathToSummarize");
chomp(my @FilePathToSummarize = <F>);
close F;

#######################################################################################
#######################################################################################
######     		     		  Iterate Over Files To Summarize  	  		   		 ######
#######################################################################################
#######################################################################################

my 	$OutputFilePath		= "$ConvDir/$Chrom.repsum.geneconv.$NrFirstFile.bed2";
open O, ">$OutputFilePath" or die ("Can't open $OutputFilePath\n");

for (my $Nr = 0; $Nr < scalar (@FilePathToSummarize); $Nr++){
	
	if ($Nr >= $NrFirstFile && $Nr < $NrFirstFile+100){
		
		my 	$FilePath 			= $FilePathToSummarize[$Nr];
		
		print "\t" . $Nr . "\t" . $FilePath . "\n";

		if ($FilePath =~ m/$ChromQm\.([A|C|G|T]*)\.repsum\.geneconv\.txt\.gz$/ ||
			$FilePath =~ m/$ChromQm\.([A|C|G|T]*)\.([A|C|G|T]*)\.repsum\.geneconv\.txt\.gz$/){
			
			if ($FileHandle->open($FilePath, "rb")){

				while(<$FileHandle>){
			
					$_ =~ s/\n//g;
				
					(my $Position, my $Change, my $Recurrence) = split(m/\t/, $_);
					
					my $BedStart = $Position-1;
					
					if ($BedStart == 10000005){
						print "Found\n";
					}
					
					print O $Chrom . "\t" . $BedStart . "\t" . $Position . "\t" . "$Change;$Recurrence\n";
				}
			}
			$FileHandle->close;
		}
		else {die("non matching file $FilePath\n");}
	}
}

close O;

system("gzip $OutputFilePath");

print "The script has finished with success\n";