use strict;
use warnings;
use Getopt::Long;
use Data::Dumper;
use IO::Zlib;
use FindBin;
use lib "$FindBin::Bin/../00_Configuration";
use ProjectConfig qw(load_config);

my %cfg = load_config();

#######################################################################################
#######################################################################################
######     		     			Initialize And Declare  	  		   			 ######
#######################################################################################
#######################################################################################

my 	$ConvDirectory 						= $cfg{paths}{conv_dir} . "/";
my 	$MappableBedFp						= "$cfg{paths}{regions_dir}/GRCh38_notinlowmappabilityall.bedsort.nochr.bed.gz";
my 	$OutputFp							= $ConvDirectory . "GcGenomeWideCoverage.txt";
			
#######################################################################################
#######################################################################################
######     		     			 	 Loop Over Directory 	  		   		 	 ######
#######################################################################################
#######################################################################################	

open O, ">$OutputFp" or die ("Can't open $OutputFp\n");

opendir (DIR, $ConvDirectory) or die ($!);
while(my $SubDir = readdir(DIR)){
	
	if ($SubDir =~ m/^\d+$/){
		
		my $SubDirPath 	= $ConvDirectory . $SubDir;
		my $NrOfPos 	= 0;
		
		opendir (SUBDIR, $SubDirPath) or die ($!);
		while(my $File = readdir(SUBDIR)){
		
			if ($File =~ m/^(.*)\.repsum\.geneconv\.sorted\.bed\.gz$/){
				
				my $Chrom = $1;
				my $BedFilePath = $SubDirPath . "/" . $File;
				
				$NrOfPos += `bedtools intersect -a $BedFilePath -b $MappableBedFp | cut -f1,2 | uniq | wc -l`;
				
				print "\t$Chrom $NrOfPos\n"; 
			}
		}
		closedir(SUBDIR);
		
		print "FINAL: " . $SubDir . "\t" . $NrOfPos . "\n";
		print O "FINAL: " . $SubDir . "\t" . $NrOfPos . "\n";
	}
}
closedir(DIR);

close O;

