use strict;
use warnings;
use Getopt::Long;
use Data::Dumper;
use IO::Zlib;
use File::Path qw(make_path);
use FindBin;
use lib "$FindBin::Bin/../00_Configuration";
use ProjectConfig qw(load_config);

my %cfg = load_config();

#######################################################################################
#######################################################################################
######     		     			 Initialize And Declare  	  		   			 ######
#######################################################################################
#######################################################################################

my 	$TempDir								= "$cfg{paths}{data_root}/temp/";
my 	$ConvDir								= $cfg{paths}{conv_dir} . "/";
my 	$RepeatLength							= 11;
my 	$Chrom									= 1;

make_path($TempDir) unless -d $TempDir;

#######################################################################################
#######################################################################################
######     		     			  	  Get Options   	  		   			 	 ######
#######################################################################################
#######################################################################################

GetOptions ("RepeatLength=s"				=>	\$RepeatLength,
			"Chrom=s"						=>	\$Chrom);

#######################################################################################
#######################################################################################
######     		     			   	 Sort And Compress  	  		   		 	 ######
#######################################################################################
#######################################################################################
	
chdir("$ConvDir/$RepeatLength/");

my 	$DataBedDir					= "$cfg{paths}{repsum_dir}/$RepeatLength/";
my 	$UnsortedOutputFilePath		= "$DataBedDir/$Chrom.repsum.geneconv.bed";
my 	$SortedOutputFilePath		= "$Chrom.repsum.geneconv.sorted.bed";

unless(-d $DataBedDir){system("mkdir -p $DataBedDir");};

if (-f "$SortedOutputFilePath.gz"){system("rm $SortedOutputFilePath.gz");}

print "zcat $Chrom.repsum.geneconv.*.bed2.gz > $UnsortedOutputFilePath\n";

system("zcat $Chrom.repsum.geneconv.*.bed2.gz > $UnsortedOutputFilePath");

print "sort -k 1,1 -k2,2n -T $TempDir $UnsortedOutputFilePath > $SortedOutputFilePath\n";

system("sort -k 1,1 -k2,2n -T $TempDir $UnsortedOutputFilePath > $SortedOutputFilePath");

print "bgzip -c $SortedOutputFilePath > $SortedOutputFilePath.gz\n";

system("bgzip -c $SortedOutputFilePath > $SortedOutputFilePath.gz");

print "tabix\n";

system("tabix -p bed $SortedOutputFilePath.gz");
system("rm $UnsortedOutputFilePath");
system("rm $SortedOutputFilePath");

print "The script has finished with success\n";

