use strict;
use warnings;
use Getopt::Long;
use Data::Dumper;
use IO::Zlib;
use FindBin;
use lib "$FindBin::Bin/../00_Configuration";
use ProjectConfig qw(load_config);

my %cfg = load_config();

#######################################################################################
#######################################################################################
######     		     			Initialize And Declare  	  		   			 ######
#######################################################################################
#######################################################################################

my 	$REP_LEN			= 41;
my 	$FileHandle			= new IO::Zlib;
my 	$Seed				= "AAAAA";
my 	%Repeats			= ();

#######################################################################################
#######################################################################################
######     		     			  	  Get Options   	  		   			 	 ######
#######################################################################################
#######################################################################################

GetOptions ("SEED=s"				=>	\$Seed,
			"REP_LEN=i"				=>	\$REP_LEN);

#######################################################################################
#######################################################################################
######     		     			Initialize And Declare  	  		   			 ######
#######################################################################################
#######################################################################################

my 	$RepeatDir			= "$cfg{paths}{repeats_dir}/$REP_LEN/";
my 	$RepSumDir			= "$cfg{paths}{repsum_dir}/$REP_LEN/";
my 	$SeedQM				= quotemeta($Seed);
my 	$OutputFilePath		= $RepSumDir . $Seed . ".repsum.txt";

unless(-d $RepSumDir){system("mkdir -p $RepSumDir");};

#######################################################################################
#######################################################################################
######     		     			Iterate Over Directory  	  		   			 ######
#######################################################################################
#######################################################################################

opendir (DIR, $RepeatDir) or die ("Can't open $RepeatDir");
while (my $File = readdir(DIR)){
	
	if ($File =~ m/^(.*?)\..*.*pos\.gz$/){
		
		my $Chrom		= $1;
		my $FilePath 	= $RepeatDir . $File;
		
		print $Chrom . "\t" . $File . "\n";
		
		if ($FileHandle->open($FilePath, "rb")){
	
			while(<$FileHandle>){
		
				$_ =~ s/\n//g;
				
				if ($_ =~ m/^$SeedQM/){
					
					(my $Repeat, my $Positions_0, my $Positions_1) = split(m/\t/, $_);
					
					if ($Positions_0 ne "/"){
						
						my @Positions_0 = split(m/\,/, $Positions_0);
						
						foreach my $Position_0 (@Positions_0){
						 
							$Repeats{$Repeat}{0}{$Chrom}{$Position_0} = undef;
						}
					}
					if ($Positions_1 ne "/"){
						
						my @Positions_1 = split(m/\,/, $Positions_1);
					
						foreach my $Position_1 (@Positions_1){
						 
							$Repeats{$Repeat}{1}{$Chrom}{$Position_1} = undef;
						}
					} 
				}
			}
		}
		$FileHandle->close();
	}
}
closedir(DIR);

#######################################################################################
#######################################################################################
######     		     					 Write Out  	  		   			 	 ######
#######################################################################################
#######################################################################################

open O, ">$OutputFilePath" or die ("Can't open $OutputFilePath\n");

foreach my $Repeat (sort keys %Repeats){
	
	print O $Repeat;
	
	if 		(exists $Repeats{$Repeat}{0}){
		
		my $CoordString = "";
		
		foreach my $Chrom (sort keys %{$Repeats{$Repeat}{0}}){
			foreach my $Position (sort {$a <=> $b} keys %{$Repeats{$Repeat}{0}{$Chrom}}){
				
				$CoordString .= "$Chrom:$Position,";
			}
		}	
		
		$CoordString =~ s/,$//g;
	
		print O "\t" . $CoordString;
	}
	else {
		
		print O "\t/";
	}
	
	if 	(exists $Repeats{$Repeat}{1}){
		
		my $CoordString = "";
		
		foreach my $Chrom (sort keys %{$Repeats{$Repeat}{1}}){
			foreach my $Position (sort {$a <=> $b} keys %{$Repeats{$Repeat}{1}{$Chrom}}){
				
				$CoordString .= "$Chrom:$Position,";
			}
		}	
		
		$CoordString =~ s/,$//g;
	
		print O "\t" . $CoordString;
	}
	else {
		
		print O "\t/";
	}
	
	print O "\n";
}

close O;

if (-f "$OutputFilePath.gz"){system("rm -f $OutputFilePath.gz");}
system("gzip $OutputFilePath");

print "The script has finished with success\n";



